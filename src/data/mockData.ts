export const generateSku = (category: string, indexOrRandom: number = 0): string => {
  const prefixMap: Record<string, string> = {
    Burgers: 'SKU-VRB',
    Pizzas: 'SKU-VRP',
    Bowls: 'SKU-VRW',
    Sides: 'SKU-VRS',
    Drinks: 'SKU-VRD',
  };
  const prefix = prefixMap[category] || 'SKU-VRX';
  const num = indexOrRandom > 0 ? (100 + indexOrRandom).toString() : Math.floor(100 + Math.random() * 900).toString();
  return `${prefix}-${num}`;
};

