export function buildRouteBetween(
  start: [number, number],
  end: [number, number]
): [number, number][] {
  const mid1: [number, number] = [start[0] + (end[0] - start[0]) * 0.35, start[1]];
  const mid2: [number, number] = [start[0] + (end[0] - start[0]) * 0.35, end[1]];
  const mid3: [number, number] = [start[0] + (end[0] - start[0]) * 0.75, end[1]];
  const waypoints = [start, mid1, mid2, mid3, end];
  return densifyRoute(waypoints, 10);
}

